import time

from fastapi import FastAPI
from pydantic import BaseModel

from opentelemetry import trace
from prometheus_client import (
    Counter,
    Gauge,
    Histogram,
    make_asgi_app,
)

from otel_common.tracing import configure_tracing


# ============================================================
# APPLICATION
# ============================================================

app = FastAPI(
    title="Cross-Service AI Observability - LLM",
    version="1.0.0",
)


# ============================================================
# MODEL CONFIGURATION
# ============================================================

MODEL_NAME = "mock-v1"


# ============================================================
# PROMETHEUS METRICS
# ============================================================

llm_requests_total = Counter(
    "llm_requests_total",
    "Total number of LLM requests",
)

llm_request_duration_seconds = Histogram(
    "llm_request_duration_seconds",
    "LLM request latency in seconds",
)

llm_prompt_length = Histogram(
    "llm_prompt_length",
    "Length of prompts sent to the LLM",
)

llm_response_length = Histogram(
    "llm_response_length",
    "Length of responses generated by the LLM",
)

llm_provider_requests_total = Counter(
    "llm_provider_requests_total",
    "Total number of requests sent to the LLM provider",
)

llm_provider_request_duration_seconds = Histogram(
    "llm_provider_request_duration_seconds",
    "LLM provider execution latency in seconds",
)

llm_active_requests = Gauge(
    "llm_active_requests",
    "Number of currently active LLM requests",
)


# ============================================================
# PROMETHEUS METRICS ENDPOINT
# ============================================================

metrics_app = make_asgi_app()

app.mount(
    "/metrics",
    metrics_app,
)


# ============================================================
# REQUEST / RESPONSE MODELS
# ============================================================


class GenerateRequest(BaseModel):
    user_id: str
    prompt: str


class GenerateResponse(BaseModel):
    response: str
    provider: str
    model: str
    service: str


# ============================================================
# MOCK PROVIDER
# ============================================================


class MockProvider:

    name = "mock"

    def generate(
        self,
        prompt: str,
    ) -> str:

        return (
            f"Mock LLM response for: {prompt}"
        )


# ============================================================
# OPEN TELEMETRY
# ============================================================

configure_tracing(
    service_name="llm-service",
    app=app,
)


tracer = trace.get_tracer(
    "llm-service"
)


provider = MockProvider()


# ============================================================
# HEALTH
# ============================================================


@app.get("/health")
async def health():

    return {
        "status": "healthy",
        "service": "llm-service",
        "provider": provider.name,
        "model": MODEL_NAME,
    }


# ============================================================
# GENERATE
# ============================================================


@app.post(
    "/generate",
    response_model=GenerateResponse,
)
async def generate(
    request: GenerateRequest,
):

    start_time = time.perf_counter()

    llm_active_requests.inc()

    response = ""

    try:

        # ====================================================
        # MAIN LLM SPAN
        # ====================================================

        with tracer.start_as_current_span(
            "llm.generate"
        ) as span:

            # ------------------------------------------------
            # PROVIDER / MODEL METADATA
            # ------------------------------------------------

            span.set_attribute(
                "llm.provider",
                provider.name,
            )

            span.set_attribute(
                "llm.model",
                MODEL_NAME,
            )

            span.set_attribute(
                "llm.prompt_length",
                len(request.prompt),
            )

            # ------------------------------------------------
            # PROMETHEUS PROMPT METRIC
            # ------------------------------------------------

            llm_prompt_length.observe(
                len(request.prompt)
            )

            # =================================================
            # PROVIDER EXECUTION
            # =================================================

            provider_start_time = (
                time.perf_counter()
            )

            llm_provider_requests_total.inc()

            with tracer.start_as_current_span(
                "llm.provider.generate"
            ) as provider_span:

                provider_span.set_attribute(
                    "llm.provider.name",
                    provider.name,
                )

                provider_span.set_attribute(
                    "llm.model",
                    MODEL_NAME,
                )

                provider_span.set_attribute(
                    "llm.prompt_length",
                    len(request.prompt),
                )

                response = provider.generate(
                    request.prompt
                )

                provider_span.set_attribute(
                    "llm.response_length",
                    len(response),
                )

            # ------------------------------------------------
            # PROVIDER LATENCY
            # ------------------------------------------------

            provider_duration = (
                time.perf_counter()
                - provider_start_time
            )

            llm_provider_request_duration_seconds.observe(
                provider_duration
            )

            # ------------------------------------------------
            # RESPONSE METADATA
            # ------------------------------------------------

            span.set_attribute(
                "llm.response_length",
                len(response),
            )

            # ------------------------------------------------
            # RESPONSE METRIC
            # ------------------------------------------------

            llm_response_length.observe(
                len(response)
            )

            # =================================================
            # RESPONSE
            # =================================================

            return GenerateResponse(
                response=response,
                provider=provider.name,
                model=MODEL_NAME,
                service="llm-service",
            )

    finally:

        # ====================================================
        # REQUEST METRICS
        # ====================================================

        llm_requests_total.inc()

        llm_request_duration_seconds.observe(
            time.perf_counter() - start_time
        )

        llm_active_requests.dec()
        